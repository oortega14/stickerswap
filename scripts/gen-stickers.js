// === Helper para emitir secciones simples al final ===
function emitSimpleSection(items, section, type) {
  for (const item of items) {
    stickers.push({
      code: item.code,
      number: n++,
      name: item.name,
      team: null,
      section,
      type,
      group: null
    });
  }
}

// === Equipos por grupo ===
for (const [groupLetter, teams] of GROUPS) {
  for (const team of teams) {
    const known = KNOWN_PLAYERS[team.code] ?? [];
    const players = []; // 18 nombres total (N2-N12 + N14-N20)
    for (let i = 0; i < 18; i++) {
      players.push(known[i] ?? `${team.section} #${i + 1}`);
    }

    // N1 escudo
    stickers.push({
      code: `${team.code}-1`,
      number: n++,
      name: `Escudo ${team.section}`,
      team: team.code,
      section: team.section,
      type: "team_badge",
      group: groupLetter
    });

    // N2..N12 → 11 jugadores
    for (let i = 0; i < 11; i++) {
      stickers.push({
        code: `${team.code}-${i + 2}`,
        number: n++,
        name: players[i],
        team: team.code,
        section: team.section,
        type: "player",
        group: groupLetter
      });
    }

    // N13 team_photo
    stickers.push({
      code: `${team.code}-13`,
      number: n++,
      name: `${team.english} Team`,
      team: team.code,
      section: team.section,
      type: "team_photo",
      group: groupLetter
    });

    // N14..N20 → 7 jugadores más
    for (let i = 0; i < 7; i++) {
      stickers.push({
        code: `${team.code}-${i + 14}`,
        number: n++,
        name: players[11 + i],
        team: team.code,
        section: team.section,
        type: "player",
        group: groupLetter
      });
    }
  }
}

